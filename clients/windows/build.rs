// The provider icons are the widget's own: like the widget's build, the PNGs in packages/scriptable/icons/, when present, are
// embedded (src/icons.rs reads them from OUT_DIR). They are the vendors' logos, so they are never committed; without them the
// rings show letters.
use std::{env, fs, path::Path};

const PROVIDERS: [&str; 3] = ["claude", "codex", "gemini"];
/** The widget's build takes icons of 64 KB at most */
const MAX_ICON_BYTES: u64 = 64 * 1024;

fn main() {
    let out = env::var("OUT_DIR").expect("OUT_DIR");
    let icons = Path::new("../../packages/scriptable/icons");
    println!("cargo:rerun-if-changed={}", icons.display());
    let mut code = String::from("// Generated by build.rs. Do not edit.\n");
    for p in PROVIDERS {
        let file = icons.join(format!("{p}.png"));
        println!("cargo:rerun-if-changed={}", file.display());
        let data = fs::read(&file)
            .ok()
            .filter(|d| d.len() as u64 <= MAX_ICON_BYTES && d.starts_with(b"\x89PNG"));
        let name = p.to_uppercase();
        match data {
            Some(d) => {
                let copy = Path::new(&out).join(format!("{p}.png"));
                fs::write(&copy, d).expect("copy icon");
                code.push_str(&format!(
                    "pub const {name}: Option<&[u8]> = Some(include_bytes!(r\"{}\"));\n",
                    copy.display()
                ));
            }
            None => code.push_str(&format!("pub const {name}: Option<&[u8]> = None;\n")),
        }
    }
    fs::write(Path::new(&out).join("icons.rs"), code).expect("write icons.rs");
    // The settings window's controls in the current Windows look (common controls 6), from a manifest in the executable
    if env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("msvc") {
        println!("cargo:rustc-link-arg-bins=/MANIFEST:EMBED");
        println!("cargo:rustc-link-arg-bins=/MANIFESTDEPENDENCY:type='win32' name='Microsoft.Windows.Common-Controls' version='6.0.0.0' processorArchitecture='*' publicKeyToken='6595b64144ccf1df' language='*'");
    }
}
